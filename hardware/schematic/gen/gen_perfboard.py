#!/usr/bin/env python3
"""Generates perfboard-layout.scr (CADCraft script): 70 x 50 mm perfboard, COMPONENT side, rev C.

Every position comes from hardware/layout/layout.json (made by layout/gen_layout.py): grid,
board, mounting holes, part bodies, leads and the TP4056 pads.  Nothing here is typed by hand
except drawing style (text heights, label offsets relative to the bodies).
Usage: python3 gen_perfboard.py [path/to/layout.json] > perfboard-layout.scr
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
LAYOUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "layout", "layout.json")
with open(LAYOUT, encoding="utf-8") as f:
    L = json.load(f)
G, B = L["grid"], L["board"]
P = G["pitch"]; X0, Y0 = G["x0"], G["y0"]; COLS = G["cols"]; NROWS = G["rows"]
BW, BH = B["size"][0], B["size"][1]; NOTCH = B["notch"]
PARTS = {p["ref"]: p for p in L["parts"]}
REV = L["rev"]

out = [f"; perfboard-layout.scr - {BW:g} x {BH:g} mm perfboard, COMPONENT side, rev {REV} (CADCraft script, mm, origin = board bottom-left, USB edge y = 0).",
       "; Generated by schematic/gen/gen_perfboard.py from layout/layout.json. Replay:",
       ";   cadcraft-cli run --metric --script-file perfboard-layout.scr --save perfboard-layout.dxf --export perfboard-layout.png",
       f"; Hole grid: one circle (handle 100) replicated with arrayrect {len(COLS)} x {NROWS} @ {P} mm. Wiring: see perfboard-solder-side."]
def cmd(id_, **p): out.append(f"{id_} {json.dumps(p, ensure_ascii=False)}")
def layer(name): cmd("layer.current", name=name)
def r3(v): return round(v, 3)
def line(*pts): cmd("line", points=[[r3(x), r3(y)] for x, y in pts])
def rect(x1, y1, x2, y2): cmd("rectang", p1=[r3(x1), r3(y1)], p2=[r3(x2), r3(y2)])
def circle(x, y, r): cmd("circle", center=[r3(x), r3(y)], radius=r)
def dot(x, y, d=1.3): cmd("donut", center=[r3(x), r3(y)], inside=0, outside=d)
def text(x, y, s, h=2, j="MC", rot=0):
    p = dict(at=[r3(x), r3(y)], text=s, height=h, justify=j)
    if rot: p["rotation"] = rot
    cmd("text", **p)
def dashed_rect(x1, y1, x2, y2, dash=2.0, gap=1.0):
    """closed dashed outline drawn as short lines (no linetype dependency)"""
    corners = [(x1, y1), (x2, y1), (x2, y2), (x1, y2), (x1, y1)]
    for (ax, ay), (bx, by) in zip(corners, corners[1:]):
        Ln = abs(bx-ax) + abs(by-ay); ux, uy = (bx-ax)/Ln, (by-ay)/Ln; s = 0.0
        while s < Ln:
            e = min(s+dash, Ln); line((ax+ux*s, ay+uy*s), (ax+ux*e, ay+uy*e)); s += dash + gap
def dashed_circle(x, y, r, n=12):
    for k in range(n):
        a0 = 360.0*k/n; cmd("arc", center=[r3(x), r3(y)], radius=r, start=a0, end=a0+360.0/n*0.6)

# --- hole grid first: the first entity gets handle 100, which the array references ---
cmd("layer.new", name="holes", color="128,128,128", current=True)
circle(X0, Y0, G["hole_d"]/2)
cmd("arrayrect", handles=["100"], rows=NROWS, cols=len(COLS), rowSpacing=P, colSpacing=P, associative=False)

cmd("lwdisplay", on=True)
cmd("layer.new", name="grid-labels", color="150,150,150")
cmd("layer.new", name="standoff", color="200,90,220")
cmd("layer.new", name="board", color=7, lineweight=0.5)
cmd("layer.new", name="components", color="0,170,230", lineweight=0.35)
cmd("layer.new", name="pins", color="255,140,0")
cmd("layer.new", name="refdes", color="255,140,0")
cmd("layer.new", name="pinnames", color="255,200,90")
cmd("layer.new", name="dims", color="0,200,0")
cmd("layer.new", name="notes", color="0,170,230")

# --- grid labels: column letters along the bottom, row numbers along the left ---
layer("grid-labels")
for i, c in enumerate(COLS):
    text(X0 + i*P, -3.0, c, 1.3)
for r in range(1, NROWS+1):
    text(-2.6, Y0 + (r-1)*P, str(r), 1.3)

# --- board outline with corner notches + mounting holes (grid holes drilled out) with their standoffs ---
layer("board")
N = NOTCH
cmd("pline", vertices=[[N, 0], [BW-N, 0], [BW-N, N], [BW, N], [BW, BH-N], [BW-N, BH-N], [BW-N, BH], [N, BH], [N, BH-N], [0, BH-N], [0, N], [N, N]], closed=True)
for m in L["mount"]:
    x, y = m["xy"]
    circle(x, y, m["d"]/2); line((x-1.5, y), (x+1.5, y)); line((x, y-1.5), (x, y+1.5))
    layer("standoff"); dashed_circle(x, y, 2.5); layer("board")
layer("refdes")
for m in L["mount"]:
    x, y = m["xy"]
    if m["name"] == "X11": text(x-3.0, y, f'{m["name"]} Ø{m["d"]}', 1.0, "MR")
    else: text(x+3.0, y, f'{m["name"]} Ø{m["d"]}', 1.0, "ML")

# --- parts ---
def body(ref): return PARTS[ref]["body"]
def holes(ref): return PARTS[ref]["holes"]
def lead_dots(ref, d=1.3):
    layer("pins")
    for h in holes(ref).values(): dot(*h["xy"], d=d)

# U1 D1 mini (module on 2 x 8 header pins)
u = PARTS["U1"]; x1, y1, x2, y2 = body("U1"); cx, cy = (x1+x2)/2, (y1+y2)/2
layer("components"); rect(x1, y1, x2, y2)
ux = L["enclosure"]["usb_micro_slot_x"] - B["cavity_offset"][0]          # micro-USB centre on the y = 0 edge
rect(ux-4, y1-1.0, ux+4, y1+5.0)
rect(cx-6, y2-4.8, cx+6, y2-0.8)                                           # PCB antenna area
layer("refdes"); text(ux, y1+2.3, "micro-USB", 1.3); text(cx, y2-2.8, "antenna", 1.3)
text(cx, cy+4.2, "U1", 2.6); text(cx, cy+1.4, "D1 mini", 1.6); text(cx, cy-0.9, "2×8 male headers", 0.9)
text(cx, cy-2.7, "long side down", 1.0); text(cx, cy-4.4, "trim flush", 1.0)
lead_dots("U1")
layer("pinnames")
for name, h in holes("U1").items():
    hx, hy = h["xy"]
    if hx < cx: text(hx+1.3, hy, name, 1.0, "ML")
    else:       text(hx-1.3, hy, name, 1.0, "MR")

# SW1 tactile 12 x 12
x1, y1, x2, y2 = body("SW1"); cx, cy = (x1+x2)/2, (y1+y2)/2
layer("components"); rect(x1, y1, x2, y2); circle(cx, cy, 7.3/2)
layer("refdes"); text(cx, cy+1.0, "SW1", 2.0); text(cx, cy-1.3, "B3F-4000", 1.1)
lead_dots("SW1")
layer("pinnames")
for name, h in holes("SW1").items():
    hx, hy = h["xy"]
    if hx < cx: text(hx+1.2, hy, name, 0.85, "ML")
    else:       text(hx-1.2, hy, name, 0.85, "MR")

# axial parts D2, R2, R3: body between the two pads, pin names above the pads, refdes + value inside the body
for ref in ("D2", "R2", "R3"):
    x1, y1, x2, y2 = body(ref); cx, cy = (x1+x2)/2, (y1+y2)/2
    hs = holes(ref); xs = sorted(h["xy"][0] for h in hs.values())
    layer("components"); rect(x1, y1, x2, y2); line((xs[0], cy), (x1, cy)); line((x2, cy), (xs[1], cy))
    if ref == "D2":                                                        # cathode band on the K side
        kx = hs["K"]["xy"][0]; bx = x1+0.8 if kx < cx else x2-0.8
        cmd("pline", vertices=[[r3(bx), r3(y1)], [r3(bx), r3(y2)]], width=0.5)
    short = PARTS[ref]["value"].split(",")[0].replace(" 1/4 W", "")
    if len(short) > 8: short = short.split()[0]                            # "1N5819 Schottky" -> "1N5819"
    layer("refdes"); text(cx, cy+0.6, ref, 0.95); text(cx, cy-0.65, short, 0.8)
    lead_dots(ref)
    layer("pinnames")
    for name, h in hs.items():
        hx, hy = h["xy"]; text(hx, hy+1.2, name, 0.75)

# C3 ceramic disc (vertical, 2.54 pitch)
x1, y1, x2, y2 = body("C3"); cx, cy = (x1+x2)/2, (y1+y2)/2
layer("components"); rect(x1, y1, x2, y2)
layer("refdes"); text(x2+0.6, cy, "C3 100 nF", 1.0, "ML")
lead_dots("C3")
layer("pinnames")
for name, h in holes("C3").items():
    hx, hy = h["xy"]; text(hx-1.1, hy, name, 0.8, "MR")

# C4 electrolytic lying flat, leads bent toward the body
x1, y1, x2, y2 = body("C4"); cx, cy = (x1+x2)/2, (y1+y2)/2
layer("components"); rect(x1, y1, x2, y2); line((x1+1.6, y1), (x1+1.6, y2))
for h in holes("C4").values():
    hx, hy = h["xy"]; line((hx, hy), (x1, hy))
layer("refdes"); text(cx+0.8, cy+0.8, "C4 100 µF", 1.1); text(cx+0.8, cy-0.9, "stripe (−) → row 14", 0.8)
lead_dots("C4")
layer("pinnames")
for name, h in holes("C4").items():
    hx, hy = h["xy"]; text(hx-1.1, hy, name, 1.0, "MR")

# J2 1 x 6 right-angle header: bent pins toward the y = 50 edge, pin names along them
x1, y1, x2, y2 = body("J2"); cx, cy = (x1+x2)/2, (y1+y2)/2
layer("components"); rect(x1, y1, x2, y2)
for h in holes("J2").values():
    hx, hy = h["xy"]; line((hx, y2), (hx, BH-1.0))
layer("refdes"); text(cx, y1-1.0, "J2 mic header", 1.0)
lead_dots("J2", 1.1)
layer("pinnames")
for name, h in holes("J2").items():
    hx, hy = h["xy"]; text(hx+0.8, y2+0.5, name, 0.8, "L", 90)

# J1 JST-PH right-angle, opening toward the x = 70 edge
x1, y1, x2, y2 = body("J1"); cx, cy = (x1+x2)/2, (y1+y2)/2
layer("components"); rect(x1, y1, x2, y2); line((x2-1.5, y1+1.2), (x2-1.5, y2-1.2))
layer("refdes"); text(cx, y2+1.1, "J1 JST-PH BAT", 1.0)
lead_dots("J1")
layer("pinnames")
for name, h in holes("J1").items():
    hx, hy = h["xy"]; text(hx+1.3, hy, name, 0.9, "ML")

# SW2 slide switch laid on its side at the x = 0 edge, lever through the wall, pins bent into column A
x1, y1, x2, y2 = body("SW2"); cx, cy = (x1+x2)/2, (y1+y2)/2
layer("components"); rect(x1, y1, x2, y2); rect(-0.8, cy-1.0, x1, cy+1.0)
for h in holes("SW2").values():
    hx, hy = h["xy"]; line((x2, hy), (hx, hy))
layer("refdes"); text(2.5, y2+1.3, "SW2", 1.0)
lead_dots("SW2")
layer("pinnames")
for name, h in holes("SW2").items():
    hx, hy = h["xy"]; text(hx+1.1, hy, name, 0.8, "ML")

# M1 TP4056 USB-C charger module: glued with foam tape, wired from its pads
x1, y1, x2, y2 = body("M1"); cx, cy = (x1+x2)/2, (y1+y2)/2
layer("components"); dashed_rect(x1, y1, x2, y2)
ucx = L["enclosure"]["usb_c_slot_x"] - B["cavity_offset"][0]
rect(ucx-4.5, y1-1.0, ucx+4.5, y1+4.0)
layer("refdes"); text(ucx, y1+2.0, "USB-C", 1.2)
text(cx, cy+3.4, "M1", 2.4); text(cx, cy+0.8, "TP4056 USB-C", 1.4); text(cx, cy-1.4, "03962A", 1.1)
text(cx, cy-3.6, "glued, foam tape", 1.1); text(cx, cy-5.4, "(no header pins)", 1.0)
layer("pins")
for name, (px, py) in L["m1_pads"].items(): circle(px, py, 0.8)
layer("pinnames")
for name, (px, py) in L["m1_pads"].items():
    if px < cx: text(px+1.2, py, name, 0.9, "ML")
    else:       text(px-1.2, py, name, 0.9, "MR")

# JP1 solder bridge pads (A10 = RST, A11 = BTN), bridged on the solder side
layer("pins")
for name, h in holes("JP1").items(): circle(*h["xy"], r=0.95)
a11 = holes("JP1")["BTN"]["xy"]
layer("pinnames"); text(a11[0]+1.3, a11[1], "JP1 (BTN)", 0.9, "ML")

# --- dimensions, scale bar, title, notes ---
layer("dims")
cmd("dimstyle", name="PCB", current=True, DIMTXT=2.2, DIMASZ=1.8, DIMEXO=1, DIMEXE=1.2, DIMDEC=1, DIMPOST="<> mm", DIMGAP=0.6)
cmd("dimlinear", p1=[0, 0], p2=[BW, 0], at=[BW/2, -8.5])
cmd("dimlinear", p1=[0, 0], p2=[0, BH], at=[-8.5, BH/2])
xa = X0 + (len(COLS)-3)*P; xb = X0 + (len(COLS)-2)*P; yt = Y0 + (NROWS-1)*P   # pitch callout on the top row
line((xa, yt+0.8), (xa, BH+2.5)); line((xb, yt+0.8), (xb, BH+2.5)); line((xa, BH+2), (xb, BH+2))
text((xa+xb)/2, BH+3.6, f"pitch {P}", 1.4)
line((0, -15.5), (10, -15.5)); line((0, -16.5), (0, -14.5)); line((5, -16.5), (5, -14.5)); line((10, -16.5), (10, -14.5))
text(12, -15.5, "10 mm", 2, "ML")
layer("notes")
text(BW/2, BH+10, f"Perfboard {BW:g} × {BH:g} mm, COMPONENT side (top view), rev {REV}", 2.5)
text(BW/2, BH+6.5, f"{P} mm grid {len(COLS)} × {NROWS} holes Ø{G['hole_d']} (A1 at {X0}, {Y0}); {NOTCH:g} × {NOTCH:g} mm corner notches; "
     f"mounting holes {', '.join(m['name'] for m in L['mount'])} drilled Ø{L['mount'][0]['d']} (Ø5 standoff dashed)", 1.5)
text(ux, -5.4, "micro-USB edge (y = 0)", 1.5); text(ucx, -5.4, "USB-C (charge)", 1.5)
text(-10.5, cy+1.0, "SW2 SS12D00G4 on its side,", 1.2, "MR"); text(-10.5, cy-1.0, "lever through the x = 0 wall", 1.2, "MR")
text(0, -19.5, "WIRING: see the solder side sheet (perfboard-solder-side) — no wires on this sheet.", 1.6, "ML")
text(0, -22.5, "Filled dots = leads soldered in grid holes; M1 is glued (foam tape) and wired from its 5 pads; JP1 = solder bridge A10–A11 (closed = battery mode).", 1.3, "ML")
text(0, -25.0, f"BT1 LiPo lies on the enclosure floor under the board; M2 INMP441 sits under the lid, 6-wire lead to J2. Source: layout/layout.json rev {REV}.", 1.3, "ML")

# --- parts table (right of the board) ---
TX = BW + 8; y = BH + 1
layer("notes"); text(TX, y, "PARTS AND LEADS", 2.0, "ML"); y -= 3.4
order = ["U1", "SW1", "D2", "R2", "R3", "C3", "C4", "J2", "J1", "SW2", "M1", "JP1"]
for ref in order:
    p = PARTS[ref]
    layer("refdes"); text(TX, y, ref, 1.6, "ML")
    layer("notes"); text(TX+8, y, p["value"], 1.4, "ML"); y -= 2.2
    pins = p["pins"]
    if pins:
        items = [f"{k}→{v}" for k, v in pins.items()]
        lines, cur = [], ""
        for it in items:
            if len(cur) + len(it) + 2 > 62: lines.append(cur); cur = it
            else: cur = it if not cur else cur + "  " + it
        lines.append(cur)
        for ln in lines:
            text(TX+8, y, ln, 1.2, "ML"); y -= 1.9
    else:
        text(TX+8, y, "pads: " + ", ".join(L["m1_pads"].keys()) + " (wired, see solder side)", 1.2, "ML"); y -= 1.9
    y -= 0.9
layer("refdes"); text(TX, y, "mount", 1.6, "ML")
layer("notes"); text(TX+8, y, "Ø2.2 holes " + ", ".join(m["name"] for m in L["mount"]) + "; keep the 8 holes around each free (Ø5 standoff)", 1.3, "ML")

cmd("zoom", mode="extents")
sys.stdout.write("\n".join(out) + "\n")
