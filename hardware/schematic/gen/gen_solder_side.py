#!/usr/bin/env python3
"""Generates perfboard-solder-side.scr (CADCraft script): the 70 x 50 mm perfboard seen from the
SOLDER side (mirrored: column X on the left, A on the right) with ALL the wires of
hardware/layout/layout.json (wires[]), the links, the solder bridge and a wiring legend.
Usage: python3 gen_solder_side.py [path/to/layout.json] > perfboard-solder-side.scr
"""
import json, math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
LAYOUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "layout", "layout.json")
with open(LAYOUT, encoding="utf-8") as f:
    L = json.load(f)
G, B = L["grid"], L["board"]
P = G["pitch"]; X0, Y0 = G["x0"], G["y0"]; COLS = G["cols"]; NROWS = G["rows"]
BW, BH = B["size"][0], B["size"][1]; NOTCH = B["notch"]
PARTS = {p["ref"]: p for p in L["parts"]}
REV = L["rev"]
def mx(x): return BW - x                 # mirror: component-side x -> solder-side x
def M(pt): return (mx(pt[0]), pt[1])

# wire colour names (gen_layout.py NET_COLOUR) -> CADCraft layer colours, chosen to read on the dark PNG and the white SVG
COLOUR = {"black": 7, "white": "185,185,185", "red": "230,40,40", "orange": "255,140,0", "yellow": "230,200,0",
          "brown": "165,95,30", "grey": "128,128,128", "violet": "165,70,220", "green": "0,190,60",
          "blue": "60,120,255", "pink": "255,105,180", "turquoise": "0,205,205", "bare": "215,185,120"}

out = [f"; perfboard-solder-side.scr - {BW:g} x {BH:g} mm perfboard, SOLDER side (mirrored view), rev {REV} (CADCraft script, mm).",
       "; Generated by schematic/gen/gen_solder_side.py from layout/layout.json. Replay:",
       ";   cadcraft-cli run --metric --script-file perfboard-solder-side.scr --save perfboard-solder-side.dxf --export perfboard-solder-side.png",
       f"; Mirror: x' = {BW:g} - x, so column X is on the left and A on the right; rows unchanged (row 1 = USB edge)."]
def cmd(id_, **p): out.append(f"{id_} {json.dumps(p, ensure_ascii=False)}")
def layer(name): cmd("layer.current", name=name)
def r3(v): return round(v, 3)
def line(*pts): cmd("line", points=[[r3(x), r3(y)] for x, y in pts])
def rect(x1, y1, x2, y2): cmd("rectang", p1=[r3(x1), r3(y1)], p2=[r3(x2), r3(y2)])
def circle(x, y, r): cmd("circle", center=[r3(x), r3(y)], radius=r)
def dot(x, y, d=1.3): cmd("donut", center=[r3(x), r3(y)], inside=0, outside=d)
def thick(a, b, w): cmd("pline", vertices=[[r3(a[0]), r3(a[1])], [r3(b[0]), r3(b[1])]], width=w)
def text(x, y, s, h=2, j="MC", rot=0):
    p = dict(at=[r3(x), r3(y)], text=s, height=h, justify=j)
    if rot: p["rotation"] = round(rot, 2)
    cmd("text", **p)
def dashed_rect(x1, y1, x2, y2, dash=1.6, gap=0.9):
    corners = [(x1, y1), (x2, y1), (x2, y2), (x1, y2), (x1, y1)]
    for (ax, ay), (bx, by) in zip(corners, corners[1:]):
        Ln = abs(bx-ax) + abs(by-ay); ux, uy = (bx-ax)/Ln, (by-ay)/Ln; s = 0.0
        while s < Ln:
            e = min(s+dash, Ln); line((ax+ux*s, ay+uy*s), (ax+ux*e, ay+uy*e)); s += dash + gap
def dashed_circle(x, y, r, n=12):
    for k in range(n):
        a0 = 360.0*k/n; cmd("arc", center=[r3(x), r3(y)], radius=r, start=a0, end=a0+360.0/n*0.6)

# --- hole grid first (handle 100 -> arrayrect); the grid is symmetric so the first hole is at the same place ---
cmd("layer.new", name="holes", color="128,128,128", current=True)
circle(mx(X0 + (len(COLS)-1)*P), Y0, G["hole_d"]/2)
cmd("arrayrect", handles=["100"], rows=NROWS, cols=len(COLS), rowSpacing=P, colSpacing=P, associative=False)

cmd("lwdisplay", on=True)
cmd("layer.new", name="grid-labels", color="150,150,150")
cmd("layer.new", name="standoff", color="200,90,220")
cmd("layer.new", name="board", color=7, lineweight=0.5)
cmd("layer.new", name="outlines", color="0,140,190")
cmd("layer.new", name="leads", color="150,150,150")
cmd("layer.new", name="refdes", color="0,170,230")
cmd("layer.new", name="pads", color="255,140,0")
cmd("layer.new", name="notes", color="0,170,230")
for name, col in COLOUR.items():
    cmd("layer.new", name=f"w-{name}", color=col, lineweight=0.5)

# --- grid labels (columns reversed), board outline, mounting holes ---
layer("grid-labels")
for i, c in enumerate(COLS):
    text(mx(X0 + i*P), -3.0, c, 1.3)
for r in range(1, NROWS+1):
    text(-2.6, Y0 + (r-1)*P, str(r), 1.3)
layer("board")
N = NOTCH
cmd("pline", vertices=[[N, 0], [BW-N, 0], [BW-N, N], [BW, N], [BW, BH-N], [BW-N, BH-N], [BW-N, BH], [N, BH], [N, BH-N], [0, BH-N], [0, N], [N, N]], closed=True)
for m in L["mount"]:
    x, y = M(m["xy"])
    circle(x, y, m["d"]/2); line((x-1.5, y), (x+1.5, y)); line((x, y-1.5), (x, y+1.5))
    layer("standoff"); dashed_circle(x, y, 2.5); layer("board")
layer("refdes")
for m in L["mount"]:
    x, y = M(m["xy"])
    text(x, y+3.3, m["name"], 1.0)

obstacles = []                                     # (x, y, r) circles that the wire labels must avoid
def ltext(x, y, s, h, j="MC"):
    """text registered as an obstacle (approximated by a chain of circles)"""
    text(x, y, s, h, j)
    w = 0.78*h*len(s); x0 = x if j == "ML" else (x - w if j == "MR" else x - w/2)
    k = 0
    while k*h <= w:
        obstacles.append((x0 + k*h + h/2, y, 0.62*h)); k += 1

# --- part outlines (dashed, for orientation) + every lead as a small dot ---
for ref, p in PARTS.items():
    if p["body"]:
        x1, y1, x2, y2 = p["body"]; a, b = mx(x2), mx(x1); cx, cy = (a+b)/2, (y1+y2)/2
        layer("outlines"); dashed_rect(a, y1, b, y2)
        layer("refdes")
        if ref == "U1":
            ltext(cx, y2-2.3, "U1 (D1 mini above)", 1.3)
        elif ref == "M1":
            ltext(cx, cy+1.0, "M1 TP4056 (glued above)", 1.2); ltext(cx, cy-1.0, "pads on the component side", 0.9)
        elif ref == "SW1":
            ltext(cx, cy, "SW1", 1.8)
        elif ref in ("D2", "R2", "R3"):
            ltext(cx, cy, ref, 0.95)
        elif ref == "C3":
            ltext(b+0.6, cy, "C3", 1.0, "ML")
        elif ref == "C4":
            ltext(cx+1, cy, "C4", 1.2)
        elif ref == "J2":
            ltext(cx, y1-1.0, "J2", 1.0)
        elif ref == "J1":
            ltext(cx, y2+1.1, "J1", 1.0)
        elif ref == "SW2":
            ltext(cx, y2+1.2, "SW2", 1.1)
    layer("leads")
    for h in p["holes"].values(): dot(*M(h["xy"]), d=1.0)
# U1 pin names: the handiest reference when soldering
layer("leads")
u = PARTS["U1"]; ucx = mx((u["body"][0]+u["body"][2])/2)
for name, h in u["holes"].items():
    hx, hy = M(h["xy"])
    if hx > ucx: ltext(hx-1.3, hy, name, 0.9, "MR")
    else:        ltext(hx+1.3, hy, name, 0.9, "ML")

# --- M1 pads (circles with names) ---
m1 = PARTS["M1"]["body"]; m1cx = mx((m1[0]+m1[2])/2)
for name, pt in L["m1_pads"].items():
    px, py = M(pt)
    layer("pads"); circle(px, py, 0.9)
    if px > m1cx: ltext(px+1.3, py, name, 0.9, "ML")
    else:         ltext(px-1.3, py, name, 0.9, "MR")

# --- wires ---
wires = L["wires"]
for p in PARTS.values():
    for h in p["holes"].values(): obstacles.append((*M(h["xy"]), 0.9))
for pt in L["m1_pads"].values(): obstacles.append((*M(pt), 1.1))
for m in L["mount"]: obstacles.append((*M(m["xy"]), 2.7))
placed = []                                        # label circles already placed
RB, HN = 1.1, 0.8                                  # number bubble radius, net name height
segs = [(M(w["a"]), M(w["b"])) for w in wires]

def label_circles(c, u, n, net):
    """circles covering the number bubble at c plus the net name running beside the wire after the bubble"""
    w = 0.78*HN*len(net)
    cs = [(c[0], c[1], RB)]
    start = RB + 0.4; k = 0
    while k*HN <= w:
        s_ = start + k*HN + HN/2
        cs.append((c[0] + u[0]*s_ + n[0]*0.9, c[1] + u[1]*s_ + n[1]*0.9, 0.62*HN)); k += 1
    return cs

def seg_dist(p, a, b):
    ax, ay = a; bx, by = b; px, py = p
    L2 = (bx-ax)**2 + (by-ay)**2
    t = max(0.0, min(1.0, ((px-ax)*(bx-ax) + (py-ay)*(by-ay)) / L2))
    return math.hypot(px - (ax + t*(bx-ax)), py - (ay + t*(by-ay)))

def clash(cs, own):
    bad = 0.0
    for (x, y, r) in cs:
        for (ox, oy, orad) in obstacles + placed:
            d = math.hypot(x-ox, y-oy)
            if d < r + orad: bad += (r + orad - d)
        for i, (a, b) in enumerate(segs):           # other wires: a label across them is unreadable
            if i == own: continue
            d = seg_dist((x, y), a, b)
            if d < r + 0.25: bad += 0.6*(r + 0.25 - d)
        if not (0.5 < x < BW-0.5 and 0.5 < y < BH-0.5): bad += 3
    return bad

def place_label(i, a, b, net):
    ax, ay = a; bx, by = b
    Ln = math.hypot(bx-ax, by-ay); dx, dy = (bx-ax)/Ln, (by-ay)/Ln
    ang = math.degrees(math.atan2(dy, dx))
    if ang > 90 or ang <= -90: ang -= 180; ux, uy = -dx, -dy      # keep the text readable
    else: ux, uy = dx, dy
    cands = []
    for t in (0.5, 0.45, 0.55, 0.4, 0.6, 0.35, 0.65, 0.3, 0.7, 0.25, 0.75, 0.2, 0.8, 0.15, 0.85):
        for off in (0.0, 1.9, -1.9, 3.2, -3.2):
            if Ln < 7 and off == 0.0: continue
            cands.append((ax + dx*Ln*t - dy*off, ay + dy*Ln*t + dx*off))
    best, bestcost = None, None
    for c in cands:
        for sgn in (1, -1):                         # name on either side of the wire
            n = (-uy*sgn, ux*sgn)
            cs = label_circles(c, (ux, uy), n, net)
            cost = clash(cs, i)
            if bestcost is None or cost < bestcost: best, bestcost = (c, n, cs), cost
        if bestcost == 0: break
    c, n, cs = best
    placed.extend(cs)
    return c, (ux, uy), n, ang

for w in wires:
    a, b = M(w["a"]), M(w["b"])
    lay = f'w-{w["colour"]}'; layer(lay)
    if w["kind"] == "link":
        thick(a, b, 0.9)
    elif w["kind"] == "bridge":
        thick(a, b, 1.6); dot((a[0]+b[0])/2, (a[1]+b[1])/2, 2.4)
    else:
        line(a, b)
    dot(*a, d=1.5); dot(*b, d=1.5)
for i, w in enumerate(wires):
    a, b = M(w["a"]), M(w["b"])
    layer(f'w-{w["colour"]}')
    c, u, n, ang = place_label(i, a, b, w["net"])
    circle(c[0], c[1], RB); text(c[0], c[1], str(w["n"]), 1.0)
    s0 = RB + 0.4
    text(c[0] + u[0]*s0 + n[0]*0.9, c[1] + u[1]*s0 + n[1]*0.9, w["net"], HN, "ML", ang)

# --- title, notes ---
layer("notes")
text(BW/2, BH+10, f"Perfboard {BW:g} × {BH:g} mm — SOLDER SIDE — mirrored view, rev {REV}", 2.5)
text(BW/2, BH+6.5, "Seen from below: column X on the LEFT, A on the RIGHT, row 1 = USB edge. Part outlines dashed (they are on the other side).", 1.5)
text(BW/2, -6.0, "USB edge (y = 0)", 1.5)
notes = ["Thick short lines = bare tinned wire links; blob between A10/A11 = JP1",
         "solder bridge (closed = battery mode). Coloured lines = insulated 26 AWG",
         "wires on this side; number in the circle = row of the legend; dots = wire",
         "ends in the holes. Max two wire ends per hole. M1 pads are on the component",
         "side (module glued): its five wires are soldered to the pads above and",
         f"come down past the module edge. Source: layout/layout.json rev {REV} (wires[]),",
         "same numbering as BUILD.md."]
for k, s_ in enumerate(notes): text(0, -9.5 - 2.2*k, s_, 1.25, "ML")

# --- legend table ---
TX = BW + 8; y = BH + 1
cols = [(0, "#"), (5, "net"), (15, "colour"), (34, "from"), (46, "to"), (57, "mm"), (64, "cut")]
layer("notes"); text(TX, y, "WIRING LEGEND (solder side)", 2.0, "ML"); y -= 3.2
for dx, name in cols: text(TX+dx, y, name, 1.3, "ML")
y -= 0.9; line((TX, y), (TX+70, y)); y -= 1.6
for w in wires:
    layer("notes")
    text(TX+cols[0][0], y, str(w["n"]), 1.3, "ML")
    text(TX+cols[1][0], y, w["net"], 1.3, "ML")
    kind = w["colour"] if w["kind"] == "wire" else f'{w["colour"]} ({w["kind"]})'
    text(TX+cols[2][0]+3.5, y, kind, 1.3, "ML")
    layer(f'w-{w["colour"]}'); thick((TX+cols[2][0], y), (TX+cols[2][0]+2.6, y), 0.7)
    layer("notes")
    text(TX+cols[3][0], y, w["frm"], 1.3, "ML")
    text(TX+cols[4][0], y, w["to"], 1.3, "ML")
    text(TX+cols[5][0], y, f'{w["mm"]:g}', 1.3, "ML")
    text(TX+cols[6][0], y, f'{w["cut_mm"]:g}' if w["kind"] == "wire" else "—", 1.3, "ML")
    y -= 2.2
y -= 0.5
text(TX, y, "mm = straight distance between the holes; cut = wire to cut (distance + 8 mm). 'bare' = 0.6 mm tinned wire.", 1.1, "ML")

cmd("zoom", mode="extents")
sys.stdout.write("\n".join(out) + "\n")
